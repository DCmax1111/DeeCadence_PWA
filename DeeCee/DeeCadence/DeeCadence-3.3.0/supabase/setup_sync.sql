-- One active browser/device per account. The device id is generated by the app
-- and stored locally. The row is written only through the security-definer
-- functions below, so a stale client cannot simply rewrite it.
create table if not exists public.deecadence_sync_devices (
  user_id uuid primary key references auth.users (id) on delete cascade,
  device_id text not null check (char_length(device_id) between 8 and 128),
  device_label text not null default '' check (char_length(device_label) <= 120),
  claimed_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

alter table public.deecadence_sync_devices enable row level security;
revoke all on table public.deecadence_sync_devices from anon, authenticated, public;

-- Claim the active device. A second device gets claimed = false and the active
-- device details unless it explicitly asks to take over the account.
create or replace function public.deecadence_claim_device(
  p_device_id text,
  p_device_label text default '',
  p_takeover boolean default false
)
returns table (claimed boolean, active_device_id text, active_device_label text, active_since timestamptz)
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_user uuid;
  v_requested text;
  v_label text;
  v_device_id text;
  v_device_label text;
  v_claimed_at timestamptz;
begin
  v_user := (select auth.uid());
  if v_user is null then raise exception 'authentication required'; end if;

  v_requested := btrim(coalesce(p_device_id, ''));
  if char_length(v_requested) < 8 or char_length(v_requested) > 128 then
    raise exception 'invalid device id';
  end if;

  v_label := left(btrim(coalesce(p_device_label, '')), 120);
  if v_label = '' then v_label := 'Another device'; end if;

  insert into public.deecadence_sync_devices as devices (user_id, device_id, device_label)
  values (v_user, v_requested, v_label)
  on conflict (user_id) do nothing;

  select d.device_id, d.device_label, d.claimed_at
    into v_device_id, v_device_label, v_claimed_at
    from public.deecadence_sync_devices d
   where d.user_id = v_user
   for update;

  if v_device_id is null then
    insert into public.deecadence_sync_devices (user_id, device_id, device_label)
    values (v_user, v_requested, v_label);
    v_device_id := v_requested;
    v_device_label := v_label;
    v_claimed_at := now();
  elsif v_device_id = v_requested then
    update public.deecadence_sync_devices
       set device_label = v_label, last_seen_at = now()
     where user_id = v_user;
    return query select true, v_device_id, v_device_label, v_claimed_at;
    return;
  elsif not coalesce(p_takeover, false) then
    return query select false, v_device_id, v_device_label, v_claimed_at;
    return;
  else
    update public.deecadence_sync_devices
       set device_id = v_requested,
           device_label = v_label,
           claimed_at = now(),
           last_seen_at = now()
     where user_id = v_user;
    return query select true, v_requested, v_label, now();
    return;
  end if;

  return query select true, v_device_id, v_device_label, v_claimed_at;
end;
$function$;

revoke all on function public.deecadence_claim_device(text, text, boolean) from public, anon, authenticated;
grant execute on function public.deecadence_claim_device(text, text, boolean) to authenticated;

