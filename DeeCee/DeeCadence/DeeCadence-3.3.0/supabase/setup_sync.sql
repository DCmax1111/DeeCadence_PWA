-- Device-checked batch ingestion. The unique (user_id, event_id) constraint
-- makes retries safe after an offline period. A session_end event also updates
-- the normalized session table. Malformed session summaries are skipped while
-- the raw event is still retained.
create or replace function public.deecadence_ingest_learning_events(
  p_device_id text,
  p_events jsonb,
  p_app_version text default ''
)
returns integer
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_user uuid;
  v_device_id text;
  v_active_device_id text;
  v_event jsonb;
  v_event_id text;
  v_event_type text;
  v_occurred_at timestamptz;
  v_data jsonb;
  v_inserted integer := 0;
  v_session_id text;
  v_started_at timestamptz;
begin
  v_user := (select auth.uid());
  if v_user is null then raise exception 'authentication required'; end if;

  v_device_id := btrim(coalesce(p_device_id, ''));
  if char_length(v_device_id) < 8 or char_length(v_device_id) > 128 then
    raise exception 'device is not registered';
  end if;

  select d.device_id into v_active_device_id
    from public.deecadence_sync_devices d
   where d.user_id = v_user;

  if v_active_device_id is null then raise exception 'device is not registered'; end if;
  if v_active_device_id <> v_device_id then raise exception 'device is not active'; end if;

  if jsonb_typeof(p_events) is distinct from 'array' then
    raise exception 'events must be a JSON array';
  end if;
  if jsonb_array_length(p_events) < 1 or jsonb_array_length(p_events) > 200 then
    raise exception 'send between 1 and 200 events';
  end if;

  for v_event in select value from jsonb_array_elements(p_events) loop
    if jsonb_typeof(v_event) is distinct from 'object' then continue; end if;

    v_event_id := btrim(coalesce(v_event->>'id', ''));
    if char_length(v_event_id) < 8 or char_length(v_event_id) > 128 then continue; end if;

    v_event_type := left(btrim(coalesce(v_event->>'type', '')), 80);
    if v_event_type = '' then continue; end if;

    v_occurred_at := case
      when coalesce(v_event->>'t', '') ~ '^[0-9]{1,15}(\.[0-9]+)?$'
        then to_timestamp((v_event->>'t')::double precision / 1000.0)
      else now()
    end;

    v_data := case
      when jsonb_typeof(v_event->'d') = 'object' then v_event->'d'
      else '{}'::jsonb
    end;
    if pg_column_size(v_data) > 32768 then v_data := '{}'::jsonb; end if;

    insert into public.deecadence_learning_events (
      user_id, event_id, event_type, occurred_at, data, device_id, app_version
    ) values (
      v_user,
      v_event_id,
      v_event_type,
      v_occurred_at,
      v_data,
      v_device_id,
      left(coalesce(p_app_version, ''), 40)
    )
    on conflict (user_id, event_id) do nothing;

    if found then v_inserted := v_inserted + 1; end if;

    if v_event_type = 'session_end'
      and nullif(btrim(coalesce(v_data->>'sessionId', '')), '') is not null then
      begin
        v_session_id := left(btrim(v_data->>'sessionId'), 128);
        if char_length(v_session_id) < 8 then v_session_id := left(v_event_id, 128); end if;
        v_started_at := case
          when coalesce(v_data->>'startedAt', '') ~ '^[0-9]{1,15}$'
            then to_timestamp((v_data->>'startedAt')::double precision / 1000.0)
          else null
        end;

        insert into public.deecadence_focus_sessions as sessions (
          user_id, session_id, started_at, ended_at, planned_minutes,
          blocks_planned, blocks_completed, block_index, partial_block,
          completed_all, ended_by, saved, pause_count, xp_earned, penalty_xp,
          task_title, source, noise_enabled, noise_playing_at_end, noise_type,
          audio_played_seconds, quick_restart, previous_session_audio,
          previous_session_completed_all, gap_since_last_session_seconds,
          block_feedback_count, last_feeling, seconds_in_reveal,
          seconds_since_block_complete, device_id, app_version
        ) values (
          v_user,
          v_session_id,
          v_started_at,
          v_occurred_at,
          nullif(v_data->>'minutes', '')::integer,
          nullif(v_data->>'blocksPlanned', '')::integer,
          nullif(v_data->>'blocksCompleted', '')::integer,
          nullif(v_data->>'blockIndex', '')::integer,
          lower(coalesce(v_data->>'partialBlock', 'false')) = 'true',
          lower(coalesce(v_data->>'completedAll', 'false')) = 'true',
          left(coalesce(v_data->>'endedBy', ''), 60),
          lower(coalesce(v_data->>'saved', 'false')) = 'true',
          coalesce(nullif(v_data->>'pauseCount', '')::integer, 0),
          coalesce(nullif(v_data->>'xpEarned', '')::integer, 0),
          coalesce(nullif(v_data->>'penaltyXp', '')::integer, 0),
          left(coalesce(v_data->>'taskTitle', ''), 120),
          left(coalesce(v_data->>'source', ''), 40),
          lower(coalesce(v_data->>'noiseEnabled', 'false')) = 'true',
          lower(coalesce(v_data->>'noisePlayingAtEnd', 'false')) = 'true',
          left(coalesce(v_data->>'noiseType', ''), 40),
          coalesce(nullif(v_data->>'audioPlayedSeconds', '')::integer, 0),
          lower(coalesce(v_data->>'quickRestart', 'false')) = 'true',
          lower(coalesce(v_data->>'previousSessionAudio', 'false')) = 'true',
          lower(coalesce(v_data->>'previousSessionCompletedAll', 'false')) = 'true',
          nullif(v_data->>'gapSinceLastSessionSeconds', '')::integer,
          coalesce(nullif(v_data->>'blockFeedbackCount', '')::integer, 0),
          left(coalesce(v_data->>'lastFeeling', ''), 80),
          coalesce(nullif(v_data->>'secondsInReveal', '')::integer, 0),
          coalesce(nullif(v_data->>'secondsSinceBlockComplete', '')::integer, 0),
          v_device_id,
          left(coalesce(p_app_version, ''), 40)
        )
        on conflict (user_id, session_id) do update set
          started_at = coalesce(excluded.started_at, sessions.started_at),
          ended_at = excluded.ended_at,
          planned_minutes = coalesce(excluded.planned_minutes, sessions.planned_minutes),
          blocks_planned = coalesce(excluded.blocks_planned, sessions.blocks_planned),
          blocks_completed = coalesce(excluded.blocks_completed, sessions.blocks_completed),
          block_index = coalesce(excluded.block_index, sessions.block_index),
          partial_block = excluded.partial_block,
          completed_all = excluded.completed_all,
          ended_by = coalesce(nullif(excluded.ended_by, ''), sessions.ended_by),
          saved = excluded.saved,
          pause_count = excluded.pause_count,
          xp_earned = excluded.xp_earned,
          penalty_xp = excluded.penalty_xp,
          task_title = coalesce(nullif(excluded.task_title, ''), sessions.task_title),
          source = coalesce(nullif(excluded.source, ''), sessions.source),
          noise_enabled = excluded.noise_enabled,
          noise_playing_at_end = excluded.noise_playing_at_end,
          noise_type = coalesce(nullif(excluded.noise_type, ''), sessions.noise_type),
          audio_played_seconds = excluded.audio_played_seconds,
          quick_restart = excluded.quick_restart,
          previous_session_audio = excluded.previous_session_audio,
          previous_session_completed_all = excluded.previous_session_completed_all,
          gap_since_last_session_seconds = coalesce(excluded.gap_since_last_session_seconds, sessions.gap_since_last_session_seconds),
          block_feedback_count = excluded.block_feedback_count,
          last_feeling = coalesce(nullif(excluded.last_feeling, ''), sessions.last_feeling),
          seconds_in_reveal = excluded.seconds_in_reveal,
          seconds_since_block_complete = excluded.seconds_since_block_complete,
          device_id = excluded.device_id,
          app_version = excluded.app_version,
          updated_at = now();
      exception when others then
        -- Keep the raw event even if a malformed summary cannot be normalized.
        null;
      end;
    end if;
  end loop;

  update public.deecadence_sync_devices
     set last_seen_at = now()
   where user_id = v_user and device_id = v_device_id;

  return v_inserted;
end;
$function$;

revoke all on function public.deecadence_ingest_learning_events(text, jsonb, text) from public, anon, authenticated;
grant execute on function public.deecadence_ingest_learning_events(text, jsonb, text) to authenticated;

-- ============================================================
-- Observed-pattern views
-- ============================================================
-- These views are for the Supabase SQL editor / service role. They are not
-- granted to app clients, so one signed-in user cannot read another account's
-- behavior. Use them to answer product questions, not to expose raw data.
drop view if exists public.deecadence_observed_patterns;
create view public.deecadence_observed_patterns as
select
  user_id,
  count(*) as sessions,
  count(*) filter (where completed_all) as completed_sessions,
  count(*) filter (where saved) as saved_sessions,
  round(100.0 * (count(*) filter (where completed_all)) / nullif(count(*), 0), 1) as completion_rate,
  round(avg(blocks_completed::numeric / nullif(blocks_planned, 0)) * 100, 1) as avg_block_completion,
  round(avg(pause_count), 1) as avg_pauses,
  round(avg(audio_played_seconds)) as avg_audio_seconds,
  count(*) filter (where audio_played_seconds > 0) as sessions_with_audio_playback,
  count(*) filter (where noise_enabled) as audio_enabled_sessions,
  count(*) filter (where noise_playing_at_end) as audio_playing_at_end_sessions,
  count(*) filter (where blocks_planned = 1) as single_block_sessions,
  count(*) filter (where blocks_planned = 1 and noise_enabled) as single_block_audio_sessions,
  count(*) filter (where blocks_planned = 1 and audio_played_seconds > 0) as single_block_audio_played_sessions,
  round(100.0 * (count(*) filter (where blocks_planned = 1 and noise_enabled and completed_all)) / nullif(count(*) filter (where blocks_planned = 1 and noise_enabled), 0), 1) as single_block_audio_completion_rate,
  count(*) filter (where quick_restart) as quick_restarts,
  count(*) filter (where quick_restart and previous_session_audio) as quick_audio_restarts,
  round(100.0 * (count(*) filter (where quick_restart and previous_session_audio)) / nullif(count(*) filter (where quick_restart), 0), 1) as quick_audio_restart_rate,
  round(avg(extract(epoch from (ended_at - started_at)) / 60.0) filter (where started_at is not null), 1) as avg_session_minutes,
  max(ended_at) as last_session_at
from public.deecadence_focus_sessions
group by user_id;

drop view if exists public.deecadence_sound_patterns;
create view public.deecadence_sound_patterns as
select
  noise_type,
  count(*) as sessions,
  count(*) filter (where completed_all) as completed_sessions,
  round(100.0 * (count(*) filter (where completed_all)) / nullif(count(*), 0), 1) as completion_rate,
  round(avg(blocks_completed::numeric / nullif(blocks_planned, 0)) * 100, 1) as avg_block_completion,
  round(avg(pause_count), 1) as avg_pauses,
  round(avg(audio_played_seconds)) as avg_audio_seconds,
  count(*) filter (where audio_played_seconds > 0) as sessions_with_audio_playback,
  count(*) filter (where blocks_planned = 1) as single_block_sessions,
  count(*) filter (where quick_restart) as quick_restarts
from public.deecadence_focus_sessions
where noise_enabled and noise_type <> ''
group by noise_type;

drop view if exists public.deecadence_reveal_decisions;
create view public.deecadence_reveal_decisions as
select
  coalesce(data->>'decision', 'unknown') as decision,
  count(*) as decisions,
  round(avg(case
    when coalesce(data->>'secondsInReveal', '') ~ '^[0-9]+(\.[0-9]+)?$'
      then (data->>'secondsInReveal')::numeric
    else null
  end), 1) as avg_seconds_in_reveal,
  count(*) filter (where lower(coalesce(data->>'feedbackGiven', 'false')) = 'true') as with_feedback,
  count(*) filter (where lower(coalesce(data->>'noiseEnabled', 'false')) = 'true') as with_audio_enabled
from public.deecadence_learning_events
where event_type = 'block_decision'
group by 1
order by decisions desc;

drop view if exists public.deecadence_audio_restart_patterns;
create view public.deecadence_audio_restart_patterns as
select
  count(*) as sessions,
  count(*) filter (where blocks_planned = 1) as single_block_sessions,
  count(*) filter (where blocks_planned = 1 and audio_played_seconds > 0) as single_block_audio_played_sessions,
  count(*) filter (where quick_restart) as quick_restarts,
  count(*) filter (where quick_restart and previous_session_audio) as quick_audio_restarts,
  round(100.0 * (count(*) filter (where quick_restart and previous_session_audio)) / nullif(count(*) filter (where quick_restart), 0), 1) as quick_audio_restart_rate,
  count(*) filter (where audio_playing_at_end) as audio_playing_at_end_sessions,
  count(*) filter (where audio_played_seconds > 0) as sessions_with_audio_playback
from public.deecadence_focus_sessions;

