-- Device-checked save. The revision check still prevents a stale device from
-- overwriting a newer cloud snapshot, and the device check prevents a device
-- that has been taken over from writing at all.
create or replace function public.deecadence_save_sync_snapshot(
  p_expected_revision bigint,
  p_payload jsonb,
  p_device_id text
)
returns table (revision bigint, updated_at timestamptz)
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_user uuid;
  v_device_id text;
  v_active_device_id text;
  v_revision bigint;
  v_updated_at timestamptz;
begin
  v_user := (select auth.uid());
  if v_user is null then raise exception 'authentication required'; end if;
  if p_expected_revision is null or p_expected_revision < 0 then
    raise exception 'expected revision must be zero or greater';
  end if;
  if jsonb_typeof(p_payload) is distinct from 'object' then raise exception 'sync snapshot must be a JSON object'; end if;
  if pg_column_size(p_payload) > 4194304 then raise exception 'sync snapshot exceeds 4 MB'; end if;

  v_device_id := btrim(coalesce(p_device_id, ''));
  if char_length(v_device_id) < 8 or char_length(v_device_id) > 128 then
    raise exception 'device is not registered';
  end if;

  select d.device_id into v_active_device_id
    from public.deecadence_sync_devices d
   where d.user_id = v_user;

  if v_active_device_id is null then raise exception 'device is not registered'; end if;
  if v_active_device_id <> v_device_id then raise exception 'device is not active'; end if;

  insert into public.deecadence_sync_state as stored (user_id, revision, payload, updated_at)
  values (v_user, 1, p_payload, now())
  on conflict (user_id) do update
    set revision = stored.revision + 1, payload = excluded.payload, updated_at = now()
    where stored.revision = p_expected_revision
  returning revision, updated_at into v_revision, v_updated_at;

  if not found then return; end if;

  update public.deecadence_sync_devices
     set last_seen_at = now()
   where user_id = v_user and device_id = v_device_id;

  return query select v_revision, v_updated_at;
end;
$function$;

revoke all on function public.deecadence_save_sync_snapshot(bigint, jsonb, text) from public, anon, authenticated;
grant execute on function public.deecadence_save_sync_snapshot(bigint, jsonb, text) to authenticated;

